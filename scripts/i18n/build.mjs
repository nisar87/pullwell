// Builds ui/i18n/<code>.js from scripts/i18n/en.txt (numbered English phrases) and scripts/i18n/<code>.txt (the same numbers, translated).
// Usage: node scripts/i18n/build.mjs        builds every language that has a .txt file, and fails when one is incomplete
import fs from 'node:fs';
import path from 'node:path';
const dir = path.dirname(new URL(import.meta.url).pathname);
const root = path.join(dir, '..', '..');
const read = f => Object.fromEntries(fs.readFileSync(f, 'utf8').split('\n').filter(l => l.trim()).map(l => { const i = l.indexOf('|'); return [l.slice(0, i), l.slice(i + 1)]; }));
const en = read(path.join(dir, 'en.txt'));
const ph = s => (s.match(/\{\d+\}/g) || []).sort().join(',');
// a value right after a letter is a plural ending (queue{1}): a translation may leave it out
const must = s => (s.match(/(?<![A-Za-z])\{\d+\}/g) || []).sort().join(',');
const has = (t, s) => must(s).split(',').filter(Boolean).every(x => t.includes(x)) && !(t.match(/\{\d+\}/g) || []).some(x => !s.includes(x));
let bad = 0;
fs.mkdirSync(path.join(root, 'ui', 'i18n'), {recursive: true});
for (const f of fs.readdirSync(dir)) {
  const m = f.match(/^([a-z]{2})\.txt$/);
  if (!m || m[1] === 'en') continue;
  const code = m[1], tr = read(path.join(dir, f)), obj = {};
  const problems = [];
  for (const [n, s] of Object.entries(en)) {
    const t = tr[n];
    if (t === undefined || t === '') { problems.push(`${code} ${n}: missing  (${s.slice(0, 50)})`); continue; }
    if (!has(t, s)) { problems.push(`${code} ${n}: values {0} differ  (${s.slice(0, 50)} -> ${t.slice(0, 50)})`); continue; }
    obj[s] = t;
  }
  for (const n of Object.keys(tr)) if (!(n in en)) problems.push(`${code} ${n}: no such phrase`);
  if (problems.length) { bad += problems.length; console.error(problems.slice(0, 25).join('\n')); if (problems.length > 25) console.error(`... ${problems.length} problems in ${code}`); continue; }
  fs.writeFileSync(path.join(root, 'ui', 'i18n', code + '.js'), `/* ${code}: generated by scripts/i18n/build.mjs from scripts/i18n/${code}.txt. Do not edit. */\nI18N.add(${JSON.stringify(code)}, ${JSON.stringify(obj, null, 0)});\n`);
  console.log(`${code}: ${Object.keys(obj).length} phrases`);
}
// the extension: its own small phrase list, built into one file the popup and the video button load
if (!bad) {
  const ed = path.join(dir, 'ext'), een = read(path.join(ed, 'en.txt'));
  let out = `/* Generated by scripts/i18n/build.mjs from scripts/i18n/ext-engine.js and scripts/i18n/ext/*.txt. Do not edit. */\n` + fs.readFileSync(path.join(dir, 'ext-engine.js'), 'utf8');
  for (const f of fs.readdirSync(ed).sort()) {
    const m = f.match(/^([a-z]{2})\.txt$/); if (!m || m[1] === 'en') continue;
    const tr = read(path.join(ed, f)), obj = {};
    for (const [n, s] of Object.entries(een)) { const t = tr[n]; if (!t || !has(t, s)) { console.error(`ext ${m[1]} ${n}: missing or values differ (${s.slice(0, 50)})`); bad++; } else obj[s] = t; }
    out += `I18N.add(${JSON.stringify(m[1])}, ${JSON.stringify(obj)});\n`;
    console.log(`ext ${m[1]}: ${Object.keys(obj).length} phrases`);
  }
  if (!bad) fs.writeFileSync(path.join(root, 'extension', 'src', 'i18n.js'), out);
}
// the engine lists exactly the languages that have a file
if (!bad) {
  const codes = fs.readdirSync(path.join(root, 'ui', 'i18n')).filter(f => /^[a-z]{2}\.js$/.test(f)).map(f => f.slice(0, 2));
  const order = ['es', 'fr', 'de', 'pt', 'ru', 'tr', 'ar', 'ur', 'hi', 'zh'];
  codes.sort((a, b) => order.indexOf(a) - order.indexOf(b));
  const f = path.join(root, 'ui', 'i18n.js'), src = fs.readFileSync(f, 'utf8');
  const line = `  const SHIPPED = ${JSON.stringify(codes).replace(/"/g, "'").replace(/,/g, ', ')};   // languages that have a file in i18n/ (written by scripts/i18n/build.mjs)`;
  fs.writeFileSync(f, src.replace(/^  const SHIPPED = .*$/m, line));
}
process.exit(bad ? 1 : 0);
